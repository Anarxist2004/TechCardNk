def _setup_style(doc: Document) -> None:
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(14)
    pf = style.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.space_after = Pt(6)


def _p(doc: Document, text: str, bullet: bool = False) -> None:
    doc.add_paragraph(text, style="List Bullet" if bullet else None)


def _h(doc: Document, text: str, level: int) -> None:
    doc.add_heading(text, level=level)


def _add_changer_section(
    doc: Document,
    index: int,
    name: str,
    source_file: str,
    purpose: str,
    inputs: list[str],
    outputs: list[str],
    algorithm: list[str],
    engineering: list[str] | None = None,
) -> None:
    _h(doc, f"{index}. {name}", 2)
    _p(doc, f"Файл реализации: {source_file}")
    _p(doc, purpose)

    _p(doc, "Входные данные:", bullet=True)
    for line in inputs:
        _p(doc, line, bullet=True)

    _p(doc, "Выходные данные / изменения в карте:", bullet=True)
    for line in outputs:
        _p(doc, line, bullet=True)

    _p(doc, "Алгоритм работы:", bullet=True)
    for line in algorithm:
        _p(doc, line, bullet=True)

    if engineering:
        _p(doc, "Инженерная часть и расчетные зависимости:", bullet=True)
        for line in engineering:
            _p(doc, line, bullet=True)


