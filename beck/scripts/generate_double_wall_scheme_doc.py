from __future__ import annotations

from datetime import datetime
from pathlib import Path

from docx import Document
from docx.enum.text import WD_LINE_SPACING
from docx.shared import Pt


ROOT = Path(r"e:\sem8\ful\Diplom_NK\beck")
OUTPUT = ROOT / "docs" / "rengen_distance_for_double_wall_scheme_detailed.docx"


def _setup(doc: Document) -> None:
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(14)
    pf = style.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.space_after = Pt(6)


def _p(doc: Document, text: str, bullet: bool = False) -> None:
    doc.add_paragraph(text, style="List Bullet" if bullet else None)


def _h(doc: Document, text: str, level: int) -> None:
    doc.add_heading(text, level=level)


def main() -> None:
    doc = Document()
    _setup(doc)

    doc.add_heading(
        "Подробное описание changer RengenDistanceForDoubleWallScheme",
        0,
    )
    _p(
        doc,
        f"Документ подготовлен по модулю "
        f"`services/Changers/ch_RengenDistanceForDoubleWallScheme.py`. "
        f"Дата: {datetime.now().strftime('%d.%m.%Y %H:%M')}.",
    )
    _p(
        doc,
        "Цель changer-а: для схемы «Кольцевое сварное соединение через две стенки» "
        "(в проекте обозначается как схема 7.2) вычислить нижнюю границу расстояния "
        "f от источника излучения до контролируемого соединения и выдать ее в виде "
        "инженерной подсказки в техкарте.",
    )

    _h(doc, "1. Входные параметры и обозначения", 1)
    for line in [
        "D — номинальный наружный диаметр трубы, мм.",
        "S_st — номинальная толщина стенки, мм.",
        "d — внутренний диаметр трубы, мм.",
        "K — чувствительность контроля, мм.",
        "Φ — размер (эквивалентный максимум) фокусного пятна ИИИ, мм.",
        "Q — уровень качества изображения (A, B, C).",
        "S_q — коэффициент по уровню качества (A->1.2, B->1.1, C->1.5).",
        "t_rad — расчетная радиационная толщина для этой схемы.",
        "m — коэффициент ступени из таблицы по качеству и толщине.",
        "c — вспомогательный коэффициент геометрического масштаба.",
        "f_min — нижняя граница расстояния от ИИИ.",
    ]:
        _p(doc, line, bullet=True)

    _h(doc, "2. Условия активации changer-а", 1)
    _p(
        doc,
        "Модуль активируется только при выборе схемы «через две стенки». "
        "При этом отдельно исключается схема 7.3 «на эллипс», так как для нее "
        "используется отдельный changer RengenDistanceForEllipseFrontalScheme.",
    )
    for line in [
        "Если схема не соответствует 7.2 — расчет не выполняется.",
        "Если не удалось прочитать D, S_st, K, Φ или Q — подсказка расстояния очищается.",
        "Если геометрия некорректна (d<=0 или D<=d) — подсказка расстояния очищается.",
    ]:
        _p(doc, line, bullet=True)

    _h(doc, "3. Формулы и инженерная модель", 1)
    _h(doc, "3.1 Геометрия", 2)
    _p(doc, "Внутренний диаметр определяется как:")
    _p(doc, "d = D - 2*S_st", bullet=True)
    _p(doc, "Условия геометрической корректности:")
    _p(doc, "d > 0", bullet=True)
    _p(doc, "D > d", bullet=True)

    _h(doc, "3.2 Коэффициенты качества", 2)
    _p(doc, "Коэффициент по классу качества S_q:")
    _p(doc, "Q = A -> S_q = 1.2", bullet=True)
    _p(doc, "Q = B -> S_q = 1.1", bullet=True)
    _p(doc, "Q = C -> S_q = 1.5", bullet=True)

    _h(doc, "3.3 Расчетная радиационная толщина и ступенчатый множитель", 2)
    _p(doc, "В реализации принята радиационная толщина:")
    _p(doc, "t_rad = 2*S_st", bullet=True)
    _p(doc, "Ступенчатый множитель m (функция _resolve_c_factor):")
    _p(doc, "для Q=A: m=2 при t_rad<=100; иначе m=3", bullet=True)
    _p(doc, "для Q=B: m=2 при t_rad<=50; m=3 при 50<t_rad<=100; иначе m=4", bullet=True)
    _p(doc, "для Q=C: m=2", bullet=True)

    _h(doc, "3.4 Вспомогательный коэффициент c", 2)
    _p(doc, "Коэффициент c вычисляется как:")
    _p(doc, "c = (m * Φ) / K", bullet=True)
    _p(
        doc,
        "Физический смысл: чем больше фокусное пятно Φ и чем ниже чувствительность K, "
        "тем выше требуемая нижняя граница расстояния.",
    )

    _h(doc, "3.5 Основная формула нижней границы расстояния", 2)
    _p(doc, "Итоговая формула, реализованная в коде:")
    _p(
        doc,
        "f_min = 1.2 * c * S_q * S_st - (D + d)/2",
        bullet=True,
    )
    _p(doc, "После расчета применяется ограничение снизу:")
    _p(doc, "если f_min < 0, то f_min := 0", bullet=True)
    _p(
        doc,
        "В карту выводится строка-подсказка вида: f>=X, "
        "где X — форматированное числовое значение f_min.",
    )

    _h(doc, "4. Пошаговый алгоритм работы (как в коде)", 1)
    for step in [
        "Чтение текущего значения схемы и проверка, что это 7.2, но не 7.3.",
        "Извлечение D, S_st, K, Φ из параметров карты.",
        "Извлечение уровня качества Q из поля «Уровень качества».",
        "Валидация входных параметров и геометрии.",
        "Расчет d = D - 2*S_st.",
        "Определение S_q по Q.",
        "Расчет t_rad = 2*S_st и подбор m по таблице диапазонов.",
        "Расчет c = (m*Φ)/K.",
        "Расчет f_min по основной формуле.",
        "Отсечение отрицательных значений: f_min = max(f_min, 0).",
        "Запись в placeholder/hint строки «f>=...».",
    ]:
        _p(doc, step, bullet=True)

    _h(doc, "5. Поведение при неполных данных", 1)
    _p(
        doc,
        "Реализация ориентирована на безопасный режим. "
        "При невозможности надежного расчета числовая рекомендация не выдается.",
    )
    for line in [
        "Отсутствие любого ключевого параметра (D, S_st, K, Φ, Q) => расчет не выполняется.",
        "Некорректная геометрия d<=0 или D<=d => расчет не выполняется.",
        "Неизвестный уровень качества => расчет не выполняется.",
        "Во всех таких случаях подсказка расстояния очищается (None), чтобы не вводить оператора в заблуждение.",
    ]:
        _p(doc, line, bullet=True)

    _h(doc, "6. Результат changer-а в техкарте", 1)
    for line in [
        "Изменяется только подсказка поля расстояния до поверхности соединения.",
        "Формат результата: «f>=X».",
        "Число X форматируется до инженерно читаемого вида (без лишних нулей).",
    ]:
        _p(doc, line, bullet=True)

    _h(doc, "7. Вывод для ВКР", 1)
    _p(
        doc,
        "RengenDistanceForDoubleWallScheme реализует параметрический инженерный расчет "
        "нижней границы расстояния для схемы 7.2 с учетом геометрии трубы, "
        "характеристики источника (фокусное пятно), требуемой чувствительности и "
        "уровня качества изображения. Модуль построен как детерминированный "
        "алгоритм с табличными коэффициентами и валидацией области применимости, "
        "что соответствует требованиям воспроизводимости расчетов в технической документации.",
    )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUTPUT)
    print(str(OUTPUT))


if __name__ == "__main__":
    main()
