from __future__ import annotations

from datetime import datetime
from pathlib import Path

from docx import Document
from docx.enum.text import WD_LINE_SPACING
from docx.shared import Pt


ROOT = Path(r"e:\sem8\ful\Diplom_NK\beck")
OUTPUT = ROOT / "docs" / "rengen_apparatus_for_panoramic_scheme_detailed.docx"


def _setup(doc: Document) -> None:
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(14)
    pf = style.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.space_after = Pt(6)


def _p(doc: Document, text: str, bullet: bool = False) -> None:
    doc.add_paragraph(text, style="List Bullet" if bullet else None)


def _h(doc: Document, text: str, level: int) -> None:
    doc.add_heading(text, level=level)


def main() -> None:
    doc = Document()
    _setup(doc)

    doc.add_heading(
        "Подробное описание changer RengenApparatusForPanoramicScheme",
        0,
    )
    _p(
        doc,
        f"Документ подготовлен для ВКР по модулю "
        f"`services/Changers/ch_RengenApparatusForPanoramicScheme.py`. "
        f"Дата: {datetime.now().strftime('%d.%m.%Y %H:%M')}.",
    )
    _p(
        doc,
        "Цель changer-а: для панорамной схемы просвечивания (схема 7.1) "
        "автоматически отфильтровать допустимые рентген-аппараты ИИИ, "
        "подставить параметры выбранного аппарата и вычислить допустимый диапазон "
        "расстояния от источника до контролируемого соединения.",
    )

    _h(doc, "1. Входные параметры и обозначения", 1)
    for line in [
        "D — номинальный диаметр трубы, мм (поле «Номинальный диаметр трубы, мм»).",
        "S — номинальная толщина стенки, мм (поле «Номинальная толщина стенки, S, мм»).",
        "d — внутренний диаметр трубы, мм.",
        "K — чувствительность контроля, мм.",
        "Φ — эквивалентный размер фокусного пятна ИИИ, мм.",
        "U_max — максимально допустимое напряжение на рентгеновской трубке, кВ, вычисляемое из таблицы voltage_tube.",
        "U_apparatus — максимальное напряжение конкретного аппарата из каталога rengen_apparatus.",
        "f — расстояние от ИИИ до поверхности контролируемого соединения, мм.",
    ]:
        _p(doc, line, bullet=True)

    _h(doc, "2. Логика активации changer-а", 1)
    _p(
        doc,
        "Расчет выполняется только если пользователь выбрал схему "
        "«Панорамное просвечивание кольцевого сварного соединения». "
        "Идентификация схемы реализована по нормализованной строке и набору "
        "обязательных фрагментов названия.",
    )
    for line in [
        "Если блок «ИСХОДНЫЕ ДАННЫЕ» отсутствует, расчет не выполняется.",
        "Если схема не панорамная, changer очищает подсказку расстояния и завершает работу.",
        "Если не хватает ключевых числовых параметров D, S или K, расчет не выполняется.",
    ]:
        _p(doc, line, bullet=True)

    _h(doc, "3. Инженерные формулы (основная часть)", 1)
    _p(doc, "Ниже приведены формулы, в точности соответствующие реализации в коде.")

    _h(doc, "3.1 Геометрия трубы", 2)
    _p(doc, "Формула внутреннего диаметра:")
    _p(doc, "d = D - 2*S", bullet=True)
    _p(doc, "Граничные проверки корректности геометрии:")
    _p(doc, "d > 0", bullet=True)
    _p(doc, "D > d", bullet=True)
    _p(doc, "d / D >= 0.8", bullet=True)
    _p(
        doc,
        "Условие d/D >= 0.8 задает область применимости панорамной схемы в "
        "рамках принятой методики. Если условие не выполнено, рекомендация по "
        "расстоянию не рассчитывается.",
    )

    _h(doc, "3.2 Ограничение по напряжению трубки", 2)
    _p(
        doc,
        "До инженерной фильтрации по фокусу применяется электрическое ограничение "
        "по напряжению трубки, получаемое из БД (таблица voltage_tube):",
    )
    _p(doc, "U_apparatus <= U_max(material, thickness)", bullet=True)
    _p(
        doc,
        "При этом в карту записывается именно U_max в поле "
        "«Напряжение на рентгеновской трубке, не более, кВ». "
        "Напряжение аппарата используется только как фильтр пригодности.",
    )

    _h(doc, "3.3 Фильтрация по фокусному пятну (ключевой инженерный критерий)", 2)
    _p(doc, "В коде вводится разность диаметров:")
    _p(doc, "Δ = D - d", bullet=True)
    _p(doc, "Основной предел для размера фокусного пятна:")
    _p(doc, "Φ <= (K * d) / (2 * Δ)", bullet=True)
    _p(doc, "Ослабленный предел (допускаемый отдельным флагом):")
    _p(doc, "Φ <= (K * d) / Δ", bullet=True)
    _p(
        doc,
        "Если аппарат проходит основной предел, он считается полностью допустимым. "
        "Если проходит только ослабленный — также допускается в каталог, но помечается "
        "внутренним признаком `requires_source_side_etalon=True`.",
    )

    _h(doc, "3.4 Расчет диапазона расстояния источника", 2)
    _p(doc, "После выбора допустимого аппарата рассчитывается диапазон f:")
    _p(doc, "f_min = Φ * (D - d) / K", bullet=True)
    _p(doc, "f_max = d / 2", bullet=True)
    _p(doc, "Итоговое ограничение, выдаваемое в техкарту:")
    _p(doc, "f_min < f <= f_max", bullet=True)
    _p(
        doc,
        "Этот диапазон записывается в placeholder/hint параметра "
        "«Расстояние от ИИИ до поверхности контролируемого сварного соединения, мм».",
    )

    _h(doc, "4. Пошаговый алгоритм работы", 1)
    steps = [
        "Проверка блока источника и факта выбора панорамной схемы.",
        "Считывание D, S, K и валидация числовых значений.",
        "Расчет d = D - 2*S, затем геометрические проверки (d>0, D>d, d/D>=0.8).",
        "Загрузка каталога аппаратов из БД.",
        "Фильтрация каталога по напряжению: U_apparatus <= U_max.",
        "Фильтрация оставшихся аппаратов по фокусному пятну через основной/ослабленный предел.",
        "Формирование options для UI (id + name).",
        "Проверка текущего выбора пользователя и попытка сопоставления с допустимым списком.",
        "Если совпадение не найдено: сброс val аппарата, фокуса, напряжения, подсказки расстояния.",
        "Если аппарат допустим: запись выбранного ИИИ, selectedId, Φ, U_max и расчет диапазона f.",
    ]
    for s in steps:
        _p(doc, s, bullet=True)

    _h(doc, "5. Поведение при неполных/ошибочных данных", 1)
    _p(
        doc,
        "Реализация ориентирована на безопасную деградацию: при любом сомнительном "
        "состоянии карта не получает некорректные числа.",
    )
    for line in [
        "Если не выбрана панорамная схема — расчет расстояния очищается.",
        "Если D, S, K не распарсены — расчет не выполняется, подсказка расстояния очищается.",
        "Если каталог аппаратов пуст — расчет прекращается без фиктивных значений.",
        "Если выбранный аппарат выпал из допустимого множества — выбор сбрасывается, forcing повторный осознанный выбор.",
        "Если фокусное пятно не извлекается из строки аппарата, такой аппарат не участвует в панорамном инженерном фильтре.",
    ]:
        _p(doc, line, bullet=True)

    _h(doc, "6. Что именно changer записывает в карту", 1)
    for line in [
        "Параметр «ИИИ»: val (имя аппарата), options (каталог), selectedId.",
        "Параметр «Размер фокусного пятна ИИИ, мм»: значение focal_spot_size выбранного аппарата.",
        "Параметр «Напряжение на рентгеновской трубке, не более, кВ»: расчетный U_max из таблицы voltage_tube.",
        "Параметр расстояния: placeholder/hint со строкой диапазона f_min<f<=f_max.",
    ]:
        _p(doc, line, bullet=True)

    _h(doc, "7. Итог для диплома", 1)
    _p(
        doc,
        "Changer RengenApparatusForPanoramicScheme реализует многоступенчатый "
        "инженерный отбор и расчет: сначала электрофизическое ограничение по напряжению "
        "трубки, затем геометрический/оптический отбор по фокусному пятну, после чего "
        "выдача диапазона рабочего расстояния. Тем самым он связывает нормативные "
        "справочники, параметры реального оборудования и геометрию объекта контроля "
        "в единую вычислительную процедуру.",
    )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUTPUT)
    print(str(OUTPUT))


if __name__ == "__main__":
    main()
